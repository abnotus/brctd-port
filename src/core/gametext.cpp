// Exe: START.EXE as stored (its data segment's strings are literal);
// Ovr: GAME.OVR; Image: the unpacked load image (resident code segments).
enum class File { Exe, Ovr, Image };

struct Where {
    Text text;
    const char* name;
    File file;
    std::uint32_t offset;   // file offset of the length byte
    std::uint8_t length;    // expected length byte
};

// Release ctd-dos-v1_00-a. START.EXE is EXEPACKed, but its data segment's
// strings are stored literally (found at these offsets). GAME.OVR offset
// = the overlay's code offset (tools/tp_overlays.py map: ovl2 0x904,
// ovl12 0x161B8, ovl15 0x1CA15, ovl17 0x1EC63, ovl23 0x27BBE, ovl25
// 0x2BA60, ovl28 0x2F067) + the CS offset the code
// pushes (session 13 scan of the push sites).
// Release ctd-dos-v1_00-a: each overlay's code offset in GAME.OVR
// (tools/tp_overlays.py map: the TPOV header is at file offset 0).
constexpr std::uint32_t kOvl100[34] = {
    0x000004, 0x0000d2, 0x000904, 0x00411a, 0x007da5, 0x0081d9, 0x00a63c, 0x00baa4, 0x00d80a,
    0x00feed, 0x010ad9, 0x0114f6, 0x0161b8, 0x01799a, 0x01b6e8, 0x01ca15, 0x01eb2e, 0x01ec63,
    0x021832, 0x024cdf, 0x02627a, 0x026744, 0x026c9f, 0x027bbe, 0x02b5c6, 0x02ba60, 0x02e013,
    0x02e204, 0x02f067, 0x0302ca, 0x030e71, 0x032886, 0x032df8, 0x032f16};

// A string pushed by overlay n's code as CS:off.
constexpr Where ovl(Text t, const char* name, int n, std::uint32_t off, std::uint8_t len) {
    return {t, name, File::Ovr, kOvl100[n] + off, len};
}
// A string in resident code segment seg (load-image offset seg*16 + off).
constexpr Where res(Text t, const char* name, std::uint32_t seg, std::uint32_t off, std::uint8_t len) {
    return {t, name, File::Image, seg * 16 + off, len};
}

