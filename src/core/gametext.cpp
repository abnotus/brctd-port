std::string identify_release(const GameFiles& files) {
    // The supported release by START.EXE's and GAME.OVR's hashes
    // (fixtures.toml); otherwise the folder explained (core/install.hpp).
    if (files.exists("START.EXE") && files.exists("GAME.OVR") &&
        release_of(sha256_hex(files.read("START.EXE")), sha256_hex(files.read("GAME.OVR"))) == kSupportedRelease)
        return kSupportedRelease;
    throw UnidentifiedRelease(examine_install(files.dir()));
}

GameText::GameText(const GameFiles& files) : release_(identify_release(files)) {
    const Bytes exe = files.read("START.EXE");
    const Bytes ovr = files.read("GAME.OVR");
    const Bytes image = exepack_image(exe);
    constexpr std::size_t kDataSegment = 0x0DB0 * 16;
    if (image.size() <= kDataSegment) throw Error("START.EXE: no data segment in the image");
    data_.assign(image.begin() + kDataSegment, image.end());
    for (const Where& w : kCtd100) {
        const Bytes& f = w.file == File::Exe ? exe : w.file == File::Ovr ? ovr : image;
        if (w.offset + 1u + w.length > f.size() || f[w.offset] != w.length)
            throw Error(std::string("game text ") + w.name + ": not at its offset in " + file_name(w.file));
        std::string s(f.begin() + w.offset + 1, f.begin() + w.offset + 1 + w.length);
        for (char c : s)
            if (static_cast<unsigned char>(c) < 0x20 || static_cast<unsigned char>(c) > 0x7E)
                throw Error(std::string("game text ") + w.name + ": not printable text");
        text_[static_cast<std::size_t>(w.text)] = std::move(s);
    }
}

std::string GameText::ds_str(std::size_t off, std::size_t max) const {
    const std::size_t n = std::min<std::size_t>(data_.at(off), max);
    if (off + 1 + n > data_.size()) throw Error("game text: data segment string at DS:" + hex(static_cast<std::uint32_t>(off), 4) + " runs past the segment");
    return std::string(data_.begin() + static_cast<std::ptrdiff_t>(off + 1), data_.begin() + static_cast<std::ptrdiff_t>(off + 1 + n));
}



